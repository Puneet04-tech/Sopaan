package com.sopaan.common;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Signing keys live outside the jar. The prototype reads the DEV keystore generated by
 * tools/gen-keys.mjs; production uses environment secrets and an offline root key.
 */
@Component
public class KeyStore {
    private static final Logger log = LoggerFactory.getLogger(KeyStore.class);
    private static final ObjectMapper MAPPER = new ObjectMapper();

    public record Key(String role, String kid, String publicKey, String seed) {
    }

    @Value("${sopaan.keys-file:../tools/dev-keys.json}")
    private String keysFile;

    private final Map<String, Key> byRole = new LinkedHashMap<>();
    private final Map<String, Key> byKid = new LinkedHashMap<>();

    @PostConstruct
    public void load() {
        Path path = Path.of(keysFile);
        if (!Files.exists(path) && Files.exists(Path.of("tools/dev-keys.json"))) {
            path = Path.of("tools/dev-keys.json");
        }
        if (Files.exists(path)) {
            try {
                JsonNode root = MAPPER.readTree(Files.readString(path)).path("keys");
                root.fields().forEachRemaining(entry -> {
                    JsonNode value = entry.getValue();
                    Key key = new Key(
                            entry.getKey(),
                            value.path("kid").asText(),
                            value.path("publicKey").asText(),
                            value.path("privateKey").asText());
                    byRole.put(key.role(), key);
                    byKid.put(key.kid(), key);
                });
                log.info("Loaded {} signing keys from {}", byRole.size(), path.toAbsolutePath());
            } catch (Exception e) {
                throw new IllegalStateException("could not read keystore " + path, e);
            }
        } else {
            log.warn("No keystore at {} — generating ephemeral keys. Signed packs will NOT verify.", path.toAbsolutePath());
            generate("root");
            generate("pack");
            generate("registry");
            generate("issuer-hub-1");
            generate("issuer-hub-2");
            generate("reviewer-1");
            generate("reviewer-2");
            generate("reviewer-3");
            generate("sponsor");
        }
    }

    private void generate(String role) {
        try {
            KeyPairGenerator generator = KeyPairGenerator.getInstance("Ed25519");
            KeyPair pair = generator.generateKeyPair();
            byte[] pkcs8 = pair.getPrivate().getEncoded();
            byte[] spki = pair.getPublic().getEncoded();
            byte[] seed = java.util.Arrays.copyOfRange(pkcs8, pkcs8.length - 32, pkcs8.length);
            byte[] pub = java.util.Arrays.copyOfRange(spki, spki.length - 32, spki.length);
            String kid = Base64.getUrlEncoder().withoutPadding()
                    .encodeToString(java.util.Arrays.copyOf(MessageDigest.getInstance("SHA-256").digest(pub), 8));
            Key key = new Key(role, kid,
                    Base64.getUrlEncoder().withoutPadding().encodeToString(pub),
                    Base64.getUrlEncoder().withoutPadding().encodeToString(seed));
            byRole.put(role, key);
            byKid.put(kid, key);
        } catch (Exception e) {
            throw new IllegalStateException("could not generate key", e);
        }
    }

    public Key key(String role) {
        Key key = byRole.get(role);
        if (key == null) throw new IllegalStateException("missing signing key: " + role);
        return key;
    }

    public Key byKid(String kid) {
        return byKid.get(kid);
    }

    public Map<String, Key> all() {
        return byRole;
    }

    public String rootKid() {
        return key("root").kid();
    }
}
